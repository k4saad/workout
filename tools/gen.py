def lattice(mode, max_kg=200.0):
    """Every total load this mode can actually make."""
    if mode not in DIV:
        return None
    base, div = BASE[mode], DIV[mode]
    budget = [(kg, c // div) for kg, c in PLATES]
    out = set()
    for combo in itertools.product(*[range(n + 1) for _, n in budget]):
        per = sum(kg * n for (kg, _), n in zip(budget, combo))
        t = round(base + 2 * per, 3)
        if t <= max_kg:
            out.add(t)
    return sorted(out)


LAT = {m: lattice(m) for m in DIV}


def snap(target, mode):
    """Closest loadable weight at or BELOW target. Never up."""
    if mode not in LAT:
        return target
    below = [a for a in LAT[mode] if a <= target + 1e-9]
    return below[-1] if below else LAT[mode][0]


def valid(kg, mode):
    return mode not in LAT or any(abs(a - kg) < 1e-6 for a in LAT[mode])


def step_at(kg, mode):
    """Smallest loadable increment above kg."""
    if mode not in LAT:
        return None
    above = [a for a in LAT[mode] if a > kg + 1e-9]
    return round(above[0] - kg, 3) if above else None


def breakdown(kg, mode):
    """Plates per side, fewest plates first. An exact search, not greedy: with
    1.25 kg and 1.0 kg plates both in the set, greedy takes a 1.25 for a
    2.0 kg side and is left 0.25 kg short."""
    if mode not in DIV:
        return None
    base, div = BASE[mode], DIV[mode]
    per = round((kg - base) / 2, 3)
    budget = [(w, c // div) for w, c in PLATES]
    best = None
    for combo in itertools.product(*[range(n + 1) for _, n in budget]):
        if abs(sum(w * n for (w, _), n in zip(budget, combo)) - per) > 1e-6:
            continue
        key = (sum(combo), [-n for n in combo])      # fewest plates, then biggest
        if best is None or key < best[0]:
            best = (key, combo)
    if best is None:
        return None
    parts = [f"{w:g}" + (f" x{n}" if n > 1 else "")
             for (w, _), n in zip(budget, best[1]) if n]
    return " + ".join(parts) if parts else "bare"


def whole_kg_gaps(mode, top):
    """Whole kilograms between the bare implement and `top` the kit cannot make."""
    have = {round(a, 3) for a in LAT[mode]}
    return [kg for kg in range(int(math.ceil(BASE[mode])), int(top) + 1)
            if float(kg) not in have]


# ----------------------------------------------------------------------------
# Projection — a best-case replay of the app's progression engine
# (app/lib/domain/progression/progression_engine.dart: rules 3a, 3b and 8) on
# this lattice. Every session is earned: every set at the top of the logged
# target with the RIR met. Deload sessions are not history (v3 Phase 1 engine
# fix), so week 9 progresses from week 7.
#
# The Build start loads, the week-12 test loads and strengthTargets are all
# derived from this, so none of them is typed and none can promise a load the
# engine cannot reach. v2 typed them, and projected a 36 kg squat that its own
# 10% jump cap froze at ~17 kg.
# ----------------------------------------------------------------------------
CREEP_STEP = 2            # ProgressionEngine.repCreepStep
DELOAD_LOAD = 0.70        # the deload block's loadMultiplier
TEST_5RM_FACTOR = 1.10    # a rested 5RM vs the week-11 working weight at RIR 1-2


def engine_step(state, p):
    """One earned session: (load, targetMin, targetMax) -> the next suggestion."""
    load, tmin, tmax = state
    mode, prog = p["loadMode"], p["progression"]
    step = step_at(load, mode)
    max_jump = load * prog["maxJumpPct"]
    creep = p["repsCreepMax"]
    can_creep = creep is not None and tmax < creep
    if step is not None and step > max_jump and can_creep:          # rule 3b
        return (load, tmin, min(tmax + CREEP_STEP, creep))
    desired = prog["incrementKg"] if prog["incrementKg"] > 0 else (step or 0)
    cap = max_jump if step is None else max(max_jump, step)
    suggested = load + min(desired, cap)                              # rule 3a
    if step is not None and step > max_jump and not can_creep:
        suggested = load + step
    snapped = snap(suggested, mode)
    if abs(snapped - snap(load, mode)) < 1e-6 and can_creep:          # rule 8
        return (load, tmin, min(tmax + CREEP_STEP, creep))
    return (snapped, p["repsMin"], p["repsMax"])


def _state(p):
    return (p["startLoadKg"], p["repsMin"], p["repsMax"])


def foundation_trajectory(fp):
    """Weeks 1-4 of a Foundation lift, plus its last logged state."""
    st, out = _state(fp), {1: fp["startLoadKg"]}
    for w in (2, 3, 4):
        st = engine_step(st, fp)
        out[w] = st[0]
    return out, st


def handoff(fp, prog, rmin, rmax, creep):
    """Week 5: the first Build session progresses from the week-4 Foundation
    log (the history lookup falls back to the same exercise), with the Build
    prescription's own progression. This IS the Build startLoadKg, so a cold
    start lands where a warm one would."""
    _, st = foundation_trajectory(fp)
    pseudo = {"loadMode": fp["loadMode"], "progression": prog, "repsCreepMax": creep,
              "repsMin": rmin, "repsMax": rmax}
    return engine_step(st, pseudo)[0]


def trajectory(bp, fp=None):
    """Week -> working load for weeks 1-11 (week 8 is the deload's 70%)."""
    out = {}
    if fp is not None:
        out, st = foundation_trajectory(fp)
        st = engine_step(st, bp)
    else:
        st = _state(bp)                     # cold start: no Foundation history
    out[5] = st[0]
    for w in (6, 7):
        st = engine_step(st, bp)
        out[w] = st[0]
    out[8] = snap(engine_step(st, bp)[0] * DELOAD_LOAD, bp["loadMode"])
    for w in (9, 10, 11):
        st = engine_step(st, bp)
        out[w] = st[0]
    return out


def test_load(traj):
    """A hard 5 in week 12, as a floor. Whole kilograms: every one loads."""
    return float(math.floor(traj[11] * TEST_5RM_FACTOR + 1e-9))


def e1rm(kg, reps):
    return kg * (1 + reps / 30)     # Epley, as the cycle seeder uses


