CARDIO_COLUMN = {"long": "longRunMin", "second": "secondRunMin"}


def CARD(table):
    assert table in CARDIO_COLUMN, table
    return {"type": "cardioTable", "table": table, "stallLimit": 99, "historyWindowDays": 21}


# Stand-in reps for a cardioTable run. apply_cardio_table() replaces them with
