def apply_cardio_table():
    """Fill in every cardioTable run from its table column: repsMin/repsMax
    are the owning block's first week (what the engine falls back to), and
    the time estimate is the LONGEST week the day is used in, inherited
    blocks included."""
    row_for = {w: r for r in PROGRAMME["cardioProgression"] for w in r["weeks"]}
    for b in PROGRAMME["blocks"]:
        if b["inheritsDaysFrom"]:
            continue
        weeks = list(b["weeks"]) + [w for i in PROGRAMME["blocks"]
                                    if i["inheritsDaysFrom"] == b["id"] for w in i["weeks"]]
        for d in b["days"]:
            for s in d["sections"]:
                for p in s["prescriptions"]:
                    if p["progression"]["type"] != "cardioTable":
                        continue
                    col = CARDIO_COLUMN[p["progression"]["table"]]
                    first = row_for[b["weeks"][0]][col]
                    assert first is not None, (p["id"], col)
                    p["repsMin"], p["repsMax"] = first[0] * 60, first[1] * 60
                    CARDIO_WORST_SEC[p["id"]] = 60 * max(
                        row_for[w][col][1] for w in weeks if row_for[w][col] is not None)


apply_cardio_table()
